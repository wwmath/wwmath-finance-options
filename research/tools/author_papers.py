# TOML emission
# ---------------------------------------------------------------------------

def q(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def val(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return q(v)
    if isinstance(v, list):
        return "[" + ", ".join(val(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {val(x)}" for k, x in v.items()) + " }"
    raise TypeError(v)


def ml(s: str) -> str:
    assert "'''" not in s
    return "'''\n" + s + "\n'''"


def emit(paper: dict) -> str:
    out = ["# Generated by research/tools/author_papers.py -- Math AST library entry.",
           "# ast fields hold canonical Math AST as JSON (see research/schema/math_ast.md).",
           "schema_version = 1", "", "[paper]"]
    for k, v in paper["paper"].items():
        out.append(f"{k} = {val(v)}")
    for s in paper["symbols"]:
        out += ["", "[[symbols]]"] + [f"{k} = {val(v)}" for k, v in s.items()]
    defs = {def_key(f["ast"]["args"][0]) for f in paper["formulas"]
            if f["ast"]["op"] in ("Eq", "Approx")}
    for f in paper["formulas"]:
        ast = f.pop("ast")
        from mathast import free_symbols
        is_def = ast["op"] in ("Eq", "Approx")
        own = def_key(ast["args"][0]) if is_def else None
        used = free_symbols(ast["args"][1] if is_def else ast)
        deps = sorted(k for k in defs if k and k != own and k.split("[")[0].split("(")[0] in used)
        out += ["", "[[formulas]]"]
        for k, v in f.items():
            out.append(f"{k} = {val(v)}")
        if deps:
            out.append(f"depends_on = {val(deps)}")
        out.append(f"latex = {ml(latex(ast))}")
        out.append(f"ast = {ml(to_json(ast))}")
    for c in paper.get("checks", []):
        out += ["", "[[checks]]"]
        for k, v in c.items():
            if k.endswith("_ast"):
                out.append(f"{k} = {ml(to_json(v))}")
            elif k == "bind":
                out.append("bind = { " + ", ".join(
                    f"{b} = {ml(to_json(x)) if isinstance(x, dict) else q(x)}"
                    for b, x in v.items()) + " }")
            else:
                out.append(f"{k} = {val(v)}")
    return "\n".join(out) + "\n"


def S(name, kind, desc, **kw):
    return {"name": name, "kind": kind, "description": desc, **kw}


def F(id_, name, kind, ast, source, **kw):
    return {"id": id_, "name": name, "kind": kind, "source": source, **kw, "ast": ast}


def src(equation=None, page=None, fidelity="verbatim-notation", verified=False, ref=None):
    s = {}
    if ref:
        s["reference"] = ref
    if equation:
        s["equation"] = equation
    if page:
        s["page"] = page
    s["fidelity"] = fidelity
    s["verified_against_pdf"] = verified
    return s


