def bates():
    Sx, V, t, T, X = sym("S"), sym("V"), sym("t"), sym("T"), sym("X")
    b, lam, kb, k = sym("b"), sym("lambdastar"), sym("kbarstar"), sym("k")
    al, be, sv, rho, de, r = (sym(x) for x in ("alpha", "betastar", "sigma_v", "rho", "delta", "r"))
    u, phi = sym("u"), sym("phi")
    iu = mul(I, u)
    core = sub(be, mul(rho, sv, iu))
    dd, gg = apply("d", u), apply("g", u)
