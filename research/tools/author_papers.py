    u, phi = sym("u"), sym("phi")
    iu = mul(I, u)
    core = sub(be, mul(rho, sv, iu))
    dd, gg = apply("d", u), apply("g", u)
    edT = exp(mul(neg(dd), T))
    rst = dict(fidelity="restated",
               ref="Bates (1996) model with the Heston CF in the Albrecher et al. (2007) form")
