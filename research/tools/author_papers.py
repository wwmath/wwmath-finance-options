    mu, kap, th, sg, rho, lam = (sym(x) for x in ("mu", "kappa", "theta", "sigma", "rho", "lambda"))
    K, r, tau, phi, j, x = sym("K"), sym("r"), sym("tau"), sym("phi"), sym("j"), sym("x")
    a = sym("a")
    bj, uj, dj, gj = idx("b", j), idx("u", j), idx("d", j), idx("g", j)
    rsp = mul(rho, sg, phi, I)  # rho sigma phi i

    def trap(name_c, name_d, name_g, name_f, sign):
        """Heston's original form (sign=+1) or Albrecher et al. 'little trap' form (sign=-1)."""
        dd = dj if sign > 0 else neg(dj)
        core = add(sub(bj, rsp), dd)                     # b_j - rho sigma phi i +/- d_j
        other = sub(sub(bj, rsp), dd)
        g = idx(name_g, j)
        edt = exp(mul(dd, tau))
        return [
            eq(idx(name_c, j), add(mul(r, phi, I, tau), mul(div(a, pow_(sg, 2)), sub(
                mul(core, tau), mul(2, log(div(sub(1, mul(g, edt)), sub(1, g)))))))),
            eq(idx(name_d, j), mul(div(core, pow_(sg, 2)),
                                   div(sub(1, edt), sub(1, mul(g, edt))))),
            eq(g, div(core, other)),
            eq(idx(name_f, j), exp(add(idx(name_c, j), mul(idx(name_d, j), v), mul(I, phi, x)))),
        ]

    orig = trap("C", "D", "g", "f", +1)
    alt = trap("Ct", "Dt", "gt", "ft", -1)
    h = src
    alb = dict(fidelity="restated", ref="Albrecher, Mayer, Schoutens & Tistaert (2007), "
                                        "'The Little Heston Trap', Wilmott Magazine, Jan 2007")
